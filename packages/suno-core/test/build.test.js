import assert from 'node:assert/strict';
import { createHash, webcrypto } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';
import vm from 'node:vm';
import { buildArtifacts, splitExports } from '../scripts/build.mjs';
import { CLIP_ID, TOKEN, encryptCtr, makeRights, syntheticMp4 } from './helpers.js';

test('reproducible: dos generaciones dan exactamente los mismos bytes', () => {
  assert.deepEqual(buildArtifacts(), buildArtifacts());
});

test('el build no contiene rutas absolutas ni fechas, y llevan cabecera de generado', () => {
  for (const a of buildArtifacts()) {
    assert.match(a.content, /@generated by @suno-api\/core/);
    assert.match(a.content, /DO NOT EDIT BY HAND/);
    assert.match(a.content, /body-sha256: [0-9a-f]{64}/);
    assert.doesNotMatch(a.content, /\/Volumes\/|\/Users\/|\/home\/|[A-Z]:\\|file:\/\//, a.rel);
    assert.doesNotMatch(a.content, /\b20\d\d-\d\d-\d\d\b/, a.rel);
    if (a.rel.endsWith('.d.ts')) continue;
    // sin dependencias ni carga de código externo
    assert.doesNotMatch(a.content, /^\s*import[\s{*(]|\brequire\(|\bimport\(/m, a.rel);
    const urls = a.content.match(/https?:\/\/[^\s'"`)]+/g) || [];
    assert.deepEqual([...new Set(urls)], ['https://d2lwuy8qc234o3.cloudfront.net'], a.rel);
  }
});

test('el body-sha256 de la cabecera valida el cuerpo (la extensión puede comprobarlo sin acceso a suno-api)', () => {
  for (const a of buildArtifacts()) {
    const cut = a.content.indexOf(' */\n') + 4;
    const head = a.content.slice(0, cut);
    const body = a.content.slice(cut);
    const declared = /body-sha256: ([0-9a-f]{64})/.exec(head)[1];
    assert.equal(createHash('sha256').update(body).digest('hex'), declared, a.rel);
  }
});

test('copia global (MAIN world): se evalúa sin módulos, expone __sunoCore y funciona con subtle inyectado', async () => {
  const globalCopy = buildArtifacts().find((a) => a.rel === 'dist/suno-core.global.js').content;
  const sandbox = { TextEncoder, TextDecoder, URL, atob, Uint8Array, ArrayBuffer, Object, Promise, Error, Array, Number, String, Math, RegExp };
  sandbox.globalThis = sandbox;
  vm.createContext(sandbox);
  vm.runInContext(globalCopy, sandbox);

  const desc = Object.getOwnPropertyDescriptor(sandbox, '__sunoCore');
  assert.ok(desc, 'debe definir __sunoCore');
  assert.equal(desc.enumerable, false);
  assert.equal(desc.writable, false);
  assert.equal(desc.configurable, false);
  const core = sandbox.__sunoCore;
  assert.ok(Object.isFrozen(core));
  assert.deepEqual(Object.keys(core).sort(), splitExports(readFileSync(new URL('../src/index.js', import.meta.url), 'utf8')).names.sort());

  // segunda carga: no redefine ni lanza
  vm.runInContext(globalCopy, sandbox);
  assert.equal(sandbox.__sunoCore, core);

  // round-trip con la copia global y el subtle de Node inyectado
  const { key, iv, rights } = makeRights();
  const c = core.createPlaybackCrypto({ subtle: webcrypto.subtle });
  const mk = await c.deriveMasterKey(TOKEN);
  const material = await c.unwrapPlaybackRights(rights, CLIP_ID, mk);
  const mp4 = syntheticMp4();
  const plain = await c.decryptPlayback(encryptCtr(mp4, key, iv), material);
  assert.equal(Buffer.compare(Buffer.from(plain), mp4), 0);
  assert.equal(core.describeClip({ id: CLIP_ID, title: 'T (Drums)', metadata: { task: 'gen_stem' } }).stemName, 'Drums');
});

test('splitExports rechaza fuentes con imports o varios exports', () => {
  assert.throws(() => splitExports("import x from 'y';\nexport { a };\n"), /imports/);
  assert.throws(() => splitExports('export const a = 1;\nexport { a };\n'), /exactamente un bloque/);
  assert.throws(() => splitExports('const a = 1;\n'), /exactamente un bloque/);
  assert.throws(() => splitExports('export { a as b };\n'), /identificadores/);
});
