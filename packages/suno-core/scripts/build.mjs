#!/usr/bin/env node
/**
 * Build de @suno-api/core para empaquetar (`npm pack`, lo lanza `prepack`).
 *
 * La fuente es src/index.js (+ src/index.d.ts) y los consumidores Node/ESM la importan tal cual
 * (`import { … } from '@suno-api/core'`). Este script solo genera lo que no puede importarse:
 *   dist/suno-core.global.js   script global para el MAIN world de Chrome (expone
 *                              globalThis.__sunoCore, no enumerable; la extensión lo carga antes de content.js)
 *
 * Los consumidores fijan una versión: dependen del .tgz (`file:vendor/suno-api-core-X.Y.Z.tgz`),
 * nunca copian código a mano. Cambiar la librería = subir versión + `npm run pack:release` + actualizar
 * la dependencia en cada repo.
 *
 * Salida reproducible: sin fechas ni rutas absolutas; cabecera con versión, sha256 de la fuente y del cuerpo.
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const PKG_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_LABEL = 'suno-api/packages/suno-core/src/index.js';
const sha256 = (text) => createHash('sha256').update(text, 'utf8').digest('hex');

const EXPORT_BLOCK_RE = /^export \{([^}]*)\};?[ \t]*$/m;

/** Extrae los nombres exportados y devuelve la fuente sin el bloque `export { ... }`. */
function splitExports(source) {
  const lines = source.split('\n');
  if (lines.some((l) => /^import[\s{*]/.test(l))) throw new Error('index.js no puede tener imports');
  const exportLines = lines.filter((l) => /^export\b/.test(l));
  const match = EXPORT_BLOCK_RE.exec(source);
  if (!match || exportLines.length !== 1) {
    throw new Error('index.js debe tener exactamente un bloque «export { ... }» y ninguna otra forma de export');
  }
  const names = match[1].split(',').map((s) => s.trim()).filter(Boolean);
  if (names.some((n) => !/^[A-Za-z_$][\w$]*$/.test(n))) throw new Error('El bloque export solo admite identificadores simples');
  return { names, body: source.replace(EXPORT_BLOCK_RE, '').replace(/\s+$/, '\n') };
}

function header({ label, version, sourceSha, target, bodySha }) {
  const lines = [
    `@generated by @suno-api/core scripts/build.mjs. DO NOT EDIT BY HAND.`,
    `Canonical source: ${label} (v${version}, source-sha256 ${sourceSha})`,
    `Target: ${target}`,
    `Regenerate: npm run build (packages/suno-core)`,
    `body-sha256: ${bodySha}`,
  ];
  return `/*\n${lines.map((l) => ` * ${l}`).join('\n')}\n */\n`;
}

function withHeader(body, meta) {
  return header({ ...meta, bodySha: sha256(body) }) + body;
}

function renderGlobal(source, meta) {
  const { names, body } = splitExports(source);
  const wrapped = [
    `(function (global) {`,
    `'use strict';`,
    body.replace(/\s+$/, ''),
    ``,
    `const api = Object.freeze({ ${names.join(', ')} });`,
    `if (global.__sunoCore === undefined) {`,
    `  Object.defineProperty(global, '__sunoCore', { value: api, enumerable: false, configurable: false, writable: false });`,
    `}`,
    `})(globalThis);`,
    ``,
  ].join('\n');
  return withHeader(wrapped, { ...meta, target: 'chrome-main-world-global (globalThis.__sunoCore)' });
}

function buildArtifacts(pkgRoot = PKG_ROOT) {
  const source = readFileSync(path.join(pkgRoot, 'src/index.js'), 'utf8');
  const version = JSON.parse(readFileSync(path.join(pkgRoot, 'package.json'), 'utf8')).version;
  const meta = { label: SOURCE_LABEL, version, sourceSha: sha256(source) };
  return [{ rel: 'dist/suno-core.global.js', content: renderGlobal(source, meta) }];
}

function build(pkgRoot = PKG_ROOT) {
  for (const art of buildArtifacts(pkgRoot)) {
    const file = path.join(pkgRoot, art.rel);
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, art.content);
  }
}

export { build, buildArtifacts, renderGlobal, splitExports };

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) build();
